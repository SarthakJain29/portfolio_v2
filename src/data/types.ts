/** Types for everything in `site.ts`. Edit content there, not here. */

export type Link = { label: string; href: string };

export type Profile = {
  name: string;
  role: string;
  location: string;
  email: string;
  /** Short line used in <meta description> and the OG image. */
  tagline: string;
  summary: string;
  /** Each string is rendered as its own paragraph. */
  about: string[];
  socials: { github: string; linkedin: string; leetcode: string };
  /** Served from /public. Add the PDF at public/resume.pdf. */
  resumeUrl: string;
  /** Shown on the "Now" readout. */
  now: { role: string; company: string; since: string; blurb: string };
  /** IANA time zone for the live local-time clock. */
  timeZone: string;
};

/** Numbers shown on the console. Only use figures from real work. */
export type Stat = { value: number; suffix?: string; label: string };

export type Experience = {
  company: string;
  role: string;
  location: string;
  /** Display string, e.g. "Jan 2026 – Present". */
  period: string;
  note?: string;
  highlights: string[];
  stack?: string[];
};

/**
 * One image of a project. `src` must be a key in `media.json` (generated by
 * scripts/import-assets.py), which supplies the real width/height.
 */
export type ProjectMedia = {
  src: string;
  alt: string;
  caption?: string;
  /** desktop = wide screenshot, mobile = phone capture, mockup = illustrative render */
  kind: "desktop" | "mobile" | "mockup";
};

export type ProjectVideo = {
  src: string;
  poster: string;
  title: string;
  /** What the video is, honestly (e.g. "motion-graphics concept, stylised mock UI"). */
  caption: string;
  /** false = captions-only video: no "click for sound" control. */
  hasAudio: boolean;
};

/** A real fallback chain from the project's README, e.g. Gemini → Groq → mock. */
export type FallbackChain = { label: string; chain: string[] };

/** A headline figure for a project (only from the project's own README/report). */
export type ProjectFact = { value: string; label: string };

/** "built" = complete, runs locally from the README; "in-progress" = still being built. */
export type ProjectStatus = "built" | "in-progress";

export type Project = {
  /** Unique, URL-safe id; also the #hash that opens the project. */
  slug: string;
  title: string;
  /** The GitHub repo name when it differs from the product name. */
  repoName?: string;
  status: ProjectStatus;
  /** 1–3 = featured order on the hero; omit for the rest. */
  featured?: 1 | 2 | 3;
  /** Short label printed on the cartridge, e.g. "FINTECH · PWA". */
  label: string;
  /** Cartridge colour (one of the palette tokens). */
  color: "orange" | "blue" | "yellow" | "green" | "pink" | "violet";
  /** One line: what it is. */
  tagline: string;
  description: string;
  /** The interesting engineering, specific and honest. */
  highlights: string[];
  stack: string[];
  fallbacks: FallbackChain[];
  facts?: ProjectFact[];
  media: ProjectMedia[];
  video?: ProjectVideo;
  /** Caveat shown under the gallery (e.g. "screens use synthetic sample data"). */
  mediaNote?: string;
  /** GitHub URL (points at the branch the description was written from). `null` = not provided. */
  github: string | null;
  /** Live demo URL. `null` = none yet (see TODO(live) in site.ts). */
  live: string | null;
  credit?: Link;
};

export type SkillGroup = { title: string; items: string[] };

export type Education = {
  school: string;
  degree: string;
  period: string;
  details: string[];
};

export type Achievement = { title: string; detail?: string };

export type SiteData = {
  profile: Profile;
  stats: Stat[];
  experience: Experience[];
  projects: Project[];
  skills: SkillGroup[];
  education: Education;
  achievements: Achievement[];
};
